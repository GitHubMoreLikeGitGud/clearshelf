/** Multilingual allergen lexicon: terms, traps, rule conflicts, precautionary and free-from patterns. */

import type { AllergenGroup } from "../llm/schemas.ts";

export type LexLang = "en" | "de" | "fr" | "es" | "it";

export interface AllergenTerm {
  term: string;
  lang: LexLang;
  group: Exclude<AllergenGroup, "none">;
  species?: string;
  /** de default is compound (substring); short egg stems use word. */
  match?: "compound" | "word";
}

export interface TrapTerm {
  term: string;
  lang: LexLang;
  group: Exclude<AllergenGroup, "none">;
  reason: string;
}

export interface RuleTerm {
  term: string;
  lang: LexLang;
  group: "tree_nut";
  ruleConflict: "coconut-tree-nut";
  reason: string;
}

export interface PrecautionaryPattern {
  lang: LexLang;
  /** Case-insensitive; matched against NFC text. */
  source: string;
}

export interface FreeFromPattern {
  lang: LexLang;
  source: string;
  claim: string;
  group?: Exclude<AllergenGroup, "none">;
}

