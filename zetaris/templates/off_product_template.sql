-- =============================================================================
-- Per-SKU Open Food Facts registration template (build plan section 3.2).
-- Not a runnable script: {gtin13} fails the allowlist on purpose. The registrar
-- generates the same statements via gateway/sqlgen.py.
--
-- Steps:
-- 1. CREATE the REST table clearshelf_off.off_{gtin13}.
-- 2. DESCRIBE it so the generator knows which optional fields exist (no source call).
-- 3. CACHE it, then COUNT(*) (expects 1).
-- 4. Re-activate product and declared_allergen from the full SKU list (one UNION ALL
--    over every SKU, generated by sqlgen; described in a comment only below).
--
-- Licence: ODbL 1.0. Data from Open Food Facts (https://world.openfoodfacts.org/),
-- licensed under the Open Database License (ODbL). Attribution required.
-- Etiquette: at least 2.5 s between statements that call Open Food Facts
-- (CREATE and CACHE; DESCRIBE makes no source call). The user-agent placeholder
-- is replaced at run time from CLEARSHELF_USER_AGENT.
-- Optional fields missing from DESCRIBE are emitted as CAST(NULL AS STRING)
-- because a direct reference fails with FIELD_NOT_FOUND. The product and
-- declared_allergen branches below assume every optional field is present.
-- =============================================================================

CREATE LIGHTNING REST TABLE off_{gtin13} FROM CLEARSHELF_OFF REQUEST(
    endpoint "https://world.openfoodfacts.org/api/v2/product/{gtin13}.json?fields=code,product_name,brands,lang,ingredients_text,ingredients_text_en,allergens_tags,traces_tags,labels_tags,countries_tags,last_modified_t",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
    user-agent "YOUR_APP_NAME YOUR_CONTACT_EMAIL"
) BODY ();

DESCRIBE clearshelf_off.off_{gtin13};

CACHE TABLE clearshelf_off.off_{gtin13};

SELECT COUNT(*) AS n FROM clearshelf_off.off_{gtin13};

-- product branch (all optional fields present); sqlgen.product_branch for the GTIN.
SELECT '{gtin13}' AS gtin, product.product_name AS product_name, product.brands AS brand, product.lang AS lang, product.ingredients_text AS ingredients_text, product.ingredients_text_en AS ingredients_text_en, array_join(product.labels_tags, ',') AS labels, CASE WHEN array_contains(product.labels_tags, 'en:vegan') THEN 'yes' ELSE 'no' END AS vegan_claim, CAST(product.last_modified_t AS STRING) AS last_modified, 'https://world.openfoodfacts.org/product/{gtin13}' AS source_url FROM clearshelf_off.off_{gtin13};

-- declared_allergen contains branch for market UK; sqlgen.declared_branch.
SELECT COALESCE(concat('{gtin13}', '|', 'UK', '|', allergen, '|', 'contains'), '') AS declared_key, '{gtin13}' AS gtin, COALESCE(concat('UK:', allergen), '') AS market_code, 'contains' AS relation, min(t) AS source_tag FROM (SELECT t, CASE t WHEN 'en:milk' THEN 'milk' WHEN 'en:gluten' THEN 'gluten_cereal' WHEN 'en:nuts' THEN 'tree_nut' WHEN 'en:soybeans' THEN 'soy' WHEN 'en:eggs' THEN 'egg' WHEN 'en:sesame-seeds' THEN 'sesame' WHEN 'en:peanuts' THEN 'peanut' WHEN 'en:crustaceans' THEN 'crustacean' WHEN 'en:molluscs' THEN 'mollusc' WHEN 'en:fish' THEN 'fish' WHEN 'en:celery' THEN 'celery' WHEN 'en:mustard' THEN 'mustard' WHEN 'en:lupin' THEN 'lupin' WHEN 'en:sulphur-dioxide-and-sulphites' THEN 'sulphite' ELSE regexp_replace(t, '^[a-z]{2}:', '') END AS allergen FROM clearshelf_off.off_{gtin13} LATERAL VIEW explode(product.allergens_tags) x AS t) s GROUP BY allergen;

